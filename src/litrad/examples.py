"""Example papers for Semantic Scholar's recommendations.

Semantic Scholar recommends recently published papers similar to *positive*
and unlike *negative* example papers. Both lists are kept as libraries
("Positive examples", "Negative examples") and regenerated by ``refresh``:

1. papers you added yourself (``ExampleChoice`` with ``include``), newest first;
2. papers chosen by the rules (``selection.s2_positive_rules`` /
   ``s2_negative_rules``), rule after rule in the configured order;

deduplicated, without papers you removed (``exclude``) and without papers
lacking a DOI (Semantic Scholar is asked by ``DOI:...``), up to
``selection.s2_positive_count`` / ``s2_negative_count`` papers.

A paper is never in both lists: adding it to one list removes it from the
other one, the rules of one list skip papers you added to the other, and the
positive rules skip papers the negative rules chose (feedback such as "not
relevant" beats "newest in your library").
Your choices survive every regeneration; ``reset`` undoes them.
"""

from dataclasses import dataclass, field
from datetime import date

from sqlmodel import Session, delete, select

from litrad import libraries
from litrad.config import Config
from litrad.db import ExampleChoice, Library, LibraryPaper, Paper, Reading, ReadStatus, now

POSITIVE, NEGATIVE = libraries.POSITIVE, libraries.NEGATIVE
KINDS = libraries.EXAMPLE_KINDS
INCLUDE, EXCLUDE = "include", "exclude"
MANUAL_TAG = "added by you"
RULE_TAG = "rule: "

# short labels (origin chips, exported labels) and explanations of every rule
RULES = {
    POSITIVE: {
        "liked": (
            "liked",
            "papers you rated 4–5 stars or read thoroughly, most recently read first",
        ),
        "read": ("read", "papers you skimmed or read (any depth), most recently read first"),
        "recent": ("newest", "papers of your library, newest publication first"),
        "impact": (
            "highest impact",
            "papers of your library by OpenAlex citation percentile (normalised by field "
            "and year), then FWCI",
        ),
        "fwci": ("highest FWCI", "papers of your library by field-weighted citation impact"),
        "cited": ("most cited", "papers of your library by number of citations"),
    },
    NEGATIVE: {
        "dismissed": ("not relevant", "papers you marked “not relevant”, most recent first"),
        "low_rated": ("rated 1–2 stars", "papers you rated 1–2 stars, most recent first"),
    },
}
# rules that draw from the libraries used for recommendations
LIBRARY_RULES = ("recent", "impact", "fwci", "cited")


def rules_of(cfg: Config, kind: str) -> list[str]:
    sel = cfg.selection
    return list(sel.s2_positive_rules if kind == POSITIVE else sel.s2_negative_rules)


def count_of(cfg: Config, kind: str) -> int:
    sel = cfg.selection
    return sel.s2_positive_count if kind == POSITIVE else sel.s2_negative_count


def rule_label(kind: str, rule: str) -> str:
    return RULES[kind][rule][0]


# --- the rules ------------------------------------------------------------------------


# only the columns the rules need: loading whole papers (abstracts) of a large
# library on every page view would be slow
COLUMNS = (
    Paper.id,
    Paper.title,
    Paper.doi,
    Paper.pub_date,
    Paper.year,
    Paper.citation_percentile,
    Paper.fwci,
    Paper.citation_count,
)
ID_CHUNK = libraries.ID_CHUNK


def _readings(session: Session, condition) -> list:
    """Papers with a reading that matches ``condition``, most recently changed first."""
    return list(
        session.exec(
            select(*COLUMNS)
            .join(Reading, Reading.paper_id == Paper.id)
            .where(condition)
            .order_by(Reading.updated_at.desc(), Paper.id)
        ).all()
    )


def library_rows(session: Session) -> list:
    """The papers of ``libraries.recommendation_library``, as light rows by id."""
    every = session.exec(select(Library).where(Library.kind.not_in(libraries.EXAMPLE_KINDS))).all()
    query = select(*COLUMNS).order_by(Paper.id)
    if not every:  # a database that has not been migrated yet
        return list(session.exec(query.where(Paper.in_library)).all())
    chosen = [lib.id for lib in every if lib.use_for_recommendations]
    if not chosen:
        return []
    return list(
        session.exec(
            query.join(LibraryPaper, LibraryPaper.paper_id == Paper.id)
            .where(LibraryPaper.library_id.in_(chosen))
            .distinct()
        ).all()
    )


def _published(row) -> date:
    return row.pub_date or date(row.year or 1900, 7, 1)


def rule_papers(session: Session, rule: str, library: list | None = None) -> list:
    """The papers a rule chooses, best first, as rows with ``id``, ``title``, ``doi``
    and the metrics (DOIs are not checked here)."""
    if rule == "liked":
        return _readings(session, (Reading.rating >= 4) | (Reading.status == ReadStatus.thorough))
    if rule == "read":
        return _readings(
            session,
            Reading.status.in_([ReadStatus.skimmed, ReadStatus.read, ReadStatus.thorough]),
        )
    if rule == "dismissed":
        return _readings(session, Reading.status == ReadStatus.dismissed)
    if rule == "low_rated":
        return _readings(session, Reading.rating.is_not(None) & (Reading.rating <= 2))
    if library is None:
        library = library_rows(session)
    # sorted() is stable: ties keep the order by id
    if rule == "recent":
        return sorted(library, key=_published, reverse=True)
    if rule == "impact":
        rated = [p for p in library if p.citation_percentile is not None]
        return sorted(rated, key=lambda p: (-p.citation_percentile, -(p.fwci or 0.0)))
    if rule == "fwci":
        return sorted((p for p in library if p.fwci is not None), key=lambda p: -p.fwci)
    if rule == "cited":
        counted = [p for p in library if p.citation_count is not None]
        return sorted(counted, key=lambda p: -p.citation_count)
    raise ValueError(f"Unknown rule '{rule}'")


def load_papers(session: Session, ids: list[int]) -> list[Paper]:
    """Whole papers in the order of ``ids``."""
    found = {}
    for start in range(0, len(ids), ID_CHUNK):
        chunk = ids[start : start + ID_CHUNK]
        found.update({p.id: p for p in session.exec(select(Paper).where(Paper.id.in_(chunk)))})
    return [found[i] for i in ids if i in found]


# --- the lists ------------------------------------------------------------------------


@dataclass
class ExampleList:
    kind: str
    library: Library
    rules: list[str]
    count: int
    papers: list[Paper] = field(default_factory=list)
    # paper id -> "added by you" or "rule: <label>"
    origins: dict[int, str] = field(default_factory=dict)
    # papers you removed (their choice, newest first)
    removed: list[tuple[Paper, ExampleChoice]] = field(default_factory=list)
    # papers the list would have taken but that have no DOI
    without_doi: int = 0
    warnings: list[str] = field(default_factory=list)

    @property
    def ids(self) -> list[str]:
        """Semantic Scholar ids of the members, in order."""
        return [f"DOI:{p.doi}" for p in self.papers]

    @property
    def manual(self) -> int:
        return sum(origin == MANUAL_TAG for origin in self.origins.values())


@dataclass
class ExampleLists:
    positive: ExampleList
    negative: ExampleList

    def __getitem__(self, kind: str) -> ExampleList:
        return self.positive if kind == POSITIVE else self.negative

    def snapshot(self) -> dict:
        """What a recommendation batch records about its examples."""
        return {
            "positive_rules": self.positive.rules,
            "positive_count": self.positive.count,
            "negative_rules": self.negative.rules,
            "negative_count": self.negative.count,
            "positives": len(self.positive.papers),
            "negatives": len(self.negative.papers),
            "positives_added_by_you": self.positive.manual,
            "negatives_added_by_you": self.negative.manual,
        }


def choices(session: Session, kind: str | None = None) -> list[ExampleChoice]:
    query = select(ExampleChoice).order_by(ExampleChoice.at.desc(), ExampleChoice.paper_id)
    if kind:
        query = query.where(ExampleChoice.kind == kind)
    return list(session.exec(query).all())


def _select(
    session: Session,
    cfg: Config,
    kind: str,
    all_choices: list[ExampleChoice],
    taken: set[int],
    library: list | None,
) -> ExampleList:
    """Members of one list, in order (without writing anything)."""
    rules, count = rules_of(cfg, kind), count_of(cfg, kind)
    result = ExampleList(kind, libraries.example_library(session, kind), rules, count)
    mine = [c for c in all_choices if c.kind == kind]
    other_includes = {c.paper_id for c in all_choices if c.kind != kind and c.action == INCLUDE}
    excluded = {c.paper_id for c in mine if c.action == EXCLUDE}
    chosen: dict[int, object] = {}  # paper id -> paper or row, in order

    included = [c for c in mine if c.action == INCLUDE]
    papers = {p.id: p for p in load_papers(session, [c.paper_id for c in mine])}
    usable = []
    for choice in included:  # newest first
        paper = papers.get(choice.paper_id)
        if paper is None:
            continue
        if not paper.doi:
            result.without_doi += 1
            continue
        usable.append(paper)
    if len(usable) > count:
        result.warnings.append(
            f"You added {len(usable)} papers to the {kind} examples, but at most {count} are "
            f"used: the {len(usable) - count} oldest additions are left out. Raise the number "
            "of examples or remove some."
        )
    for paper in usable[:count]:
        chosen[paper.id] = paper
        result.origins[paper.id] = MANUAL_TAG

    for rule in rules:
        if len(chosen) >= count:
            break
        for paper in rule_papers(session, rule, library):
            if len(chosen) >= count:
                break
            if (
                paper.id in chosen
                or paper.id in excluded
                or paper.id in other_includes
                or paper.id in taken
            ):
                continue
            if not paper.doi:
                result.without_doi += 1
                excluded.add(paper.id)  # counted once, also if another rule chooses it
                continue
            chosen[paper.id] = paper
            result.origins[paper.id] = RULE_TAG + rule_label(kind, rule)
    result.papers = load_papers(session, list(chosen))
    result.removed = [
        (papers[c.paper_id], c) for c in mine if c.action == EXCLUDE and c.paper_id in papers
    ]
    if kind == POSITIVE and not result.papers and not rules:
        result.warnings.append(
            "No rule chooses positive examples and you added none: Semantic Scholar's "
            "recommendations are skipped."
        )
    return result


def _store(session: Session, result: ExampleList) -> None:
    """Make the library's members exactly the list (origin as its label)."""
    wanted = {p.id: [result.origins[p.id]] for p in result.papers}
    entries = session.exec(
        select(LibraryPaper).where(LibraryPaper.library_id == result.library.id)
    ).all()
    for entry in entries:
        tags = wanted.pop(entry.paper_id, None)
        if tags is None:
            session.delete(entry)
        elif list(entry.tags or []) != tags:
            entry.tags = tags
            session.add(entry)
    for paper_id, tags in wanted.items():
        session.add(
            LibraryPaper(library_id=result.library.id, paper_id=paper_id, folders=[], tags=tags)
        )


def compute(session: Session, cfg: Config) -> ExampleLists:
    """Both lists as ``refresh`` would store them (the libraries are created if missing)."""
    all_choices = choices(session)
    library = None
    if any(rule in LIBRARY_RULES for rule in rules_of(cfg, POSITIVE)):
        library = library_rows(session)
    # a paper is never in both lists: your additions win, then the negative rules
    # (a paper you dismissed is no positive example, even if it is in your library)
    negative = _select(session, cfg, NEGATIVE, all_choices, set(), library)
    positive = _select(
        session, cfg, POSITIVE, all_choices, {p.id for p in negative.papers}, library
    )
    return ExampleLists(positive, negative)


def refresh(session: Session, cfg: Config) -> ExampleLists:
    """Regenerate both example libraries from the rules and your choices.

    Idempotent; flushes, the caller commits.
    """
    lists = compute(session, cfg)
    for kind in KINDS:
        _store(session, lists[kind])
    session.flush()
    return lists


# --- your choices ----------------------------------------------------------------------


def _check(kind: str) -> None:
    if kind not in KINDS:
        raise ValueError(f"Choose 'positive' or 'negative', not '{kind}'")


def _set(session: Session, paper_id: int, kind: str, action: str) -> None:
    choice = session.get(ExampleChoice, (paper_id, kind))
    if choice is None:
        choice = ExampleChoice(paper_id=paper_id, kind=kind, action=action)
    choice.action, choice.at = action, now()
    session.add(choice)


def include(session: Session, paper: Paper, kind: str) -> None:
    """Use a paper as example of ``kind`` (and not as example of the other kind)."""
    _check(kind)
    _set(session, paper.id, kind, INCLUDE)
    other = NEGATIVE if kind == POSITIVE else POSITIVE
    choice = session.get(ExampleChoice, (paper.id, other))
    if choice is not None and choice.action == INCLUDE:
        session.delete(choice)
    session.flush()


def remove(session: Session, cfg: Config, paper_id: int, kind: str) -> bool:
    """Take a paper out of a list: drop your addition, and keep the rules from
    choosing it again. Returns True if it was in the list or added by you."""
    _check(kind)
    choice = session.get(ExampleChoice, (paper_id, kind))
    changed = False
    if choice is not None and choice.action == INCLUDE:
        session.delete(choice)
        session.flush()
        changed = True
    if any(p.id == paper_id for p in compute(session, cfg)[kind].papers):
        _set(session, paper_id, kind, EXCLUDE)
        changed = True
    session.flush()
    return changed


def restore(session: Session, paper_id: int, kind: str) -> bool:
    """Let the rules choose a paper you removed again."""
    _check(kind)
    choice = session.get(ExampleChoice, (paper_id, kind))
    if choice is None or choice.action != EXCLUDE:
        return False
    session.delete(choice)
    session.flush()
    return True


def not_an_example(session: Session, cfg: Config, paper_id: int) -> bool:
    """Neither a positive nor a negative example."""
    return any([remove(session, cfg, paper_id, kind) for kind in KINDS])


def reset(session: Session, kind: str) -> int:
    """Undo all your choices of one list; returns how many there were."""
    _check(kind)
    found = len(choices(session, kind))
    session.exec(delete(ExampleChoice).where(ExampleChoice.kind == kind))
    session.flush()
    return found


def role(lists: ExampleLists, paper_id: int) -> tuple[str, str] | None:
    """(kind, origin) if the paper is an example now."""
    for kind in KINDS:
        origin = lists[kind].origins.get(paper_id)
        if origin is not None:
            return kind, origin
    return None
